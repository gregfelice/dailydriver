"""Claude Code adapter — preset swap + truecolor-stripping wrapper.

Two responsibilities:

1. Flip ``theme`` in ``~/.claude/settings.json`` between the user's prior
   preset and ``"dark"`` (the preset we use under nightpanel).
2. Install a wrapper at ``~/.local/bin/claude`` that strips ``COLORTERM``
   before exec'ing the real binary whenever nightpanel is active. With
   truecolor disabled, Claude Code's output (including diff backgrounds
   and syntax highlighting) flows through the 16-color ANSI palette —
   which the alacritty adapter renders as strict green/amber/red.

The wrapper is self-aware: it checks the ``nightpanel-active`` sentinel
at run time, so a single binary handles both states correctly. Revert
doesn't need to undo the wrapper.
"""

from __future__ import annotations

import json
import logging
import os
import shutil
from pathlib import Path
from typing import Literal

from ..palette import Palette
from .base import Adapter

_LOG = logging.getLogger(__name__)

_SETTINGS    = Path.home() / ".claude" / "settings.json"
_NP_THEME    = "dark"  # the preset we engage when nightpanel is on

# Wrapper install paths
_WRAPPER     = Path.home() / ".local" / "bin" / "claude"
_REAL_DIR    = Path.home() / ".local" / "share" / "claude" / "versions"
_NP_ACTIVE   = Path.home() / ".config" / "nightpanel" / "nightpanel-active"

_WRAPPER_MARKER = "# nightpanel-claude-wrapper"

_WRAPPER_SCRIPT = f"""\
#!/usr/bin/env bash
{_WRAPPER_MARKER}
# nightpanel-aware Claude Code wrapper.
# When nightpanel is active, strips COLORTERM so Claude Code falls back to
# 16-color rendering — every escape flows through the terminal ANSI palette
# (which nightpanel paints in strict green/amber/red). When nightpanel is
# off, the wrapper is a transparent passthrough. Generated by
# nightpanel.adapters.claude_code — regenerate by calling apply().

REAL=$(ls -1 "$HOME/.local/share/claude/versions"/* 2>/dev/null | sort -V | tail -1)
if [ -z "$REAL" ] || [ ! -x "$REAL" ]; then
    echo "claude: real binary not found in $HOME/.local/share/claude/versions/" >&2
    exit 127
fi

if [ -e "$HOME/.config/nightpanel/nightpanel-active" ]; then
    exec env -u COLORTERM "$REAL" "$@"
else
    exec "$REAL" "$@"
fi
"""


class ClaudeCodeAdapter(Adapter):
    name = "claude_code"

    def installed(self) -> bool:
        # The CLI may not be on $PATH if installed via a manager; check the
        # settings dir instead. Either signal is good enough.
        return bool(shutil.which("claude")) or _SETTINGS.exists()

    def snapshot(self) -> dict:
        return {
            "theme":            self._read_theme(),
            "wrapper_existed":  _WRAPPER.exists(),
            "wrapper_was_link": _WRAPPER.is_symlink(),
            "wrapper_link_to":  os.readlink(_WRAPPER) if _WRAPPER.is_symlink() else None,
        }

    def apply(self, palette: Palette) -> None:
        self._write_theme(_NP_THEME)
        self._install_wrapper()

    def revert(self, snapshot: dict) -> None:
        prev = snapshot.get("theme") or "auto"
        self._write_theme(prev)
        # Leave the wrapper in place — it's self-aware via the active-file
        # sentinel and becomes a transparent passthrough when NP is off.

    def verify(self, expected: Literal["on", "off"]) -> bool:
        # Theme-on AND wrapper-installed both required for strict mode.
        theme_on   = self._read_theme() == _NP_THEME
        wrapper_on = self._wrapper_installed()
        on = theme_on and wrapper_on
        return on if expected == "on" else not on

    # ── helpers ──
    def _read_settings(self) -> dict:
        try:
            return json.loads(_SETTINGS.read_text())
        except (OSError, json.JSONDecodeError):
            return {}

    def _read_theme(self) -> str | None:
        return self._read_settings().get("theme")

    def _write_theme(self, value: str) -> None:
        try:
            _SETTINGS.parent.mkdir(parents=True, exist_ok=True)
            data = self._read_settings()
            data["theme"] = value
            # Preserve key order + indentation matching the existing file style.
            _SETTINGS.write_text(json.dumps(data, indent=2) + "\n")
        except OSError as e:
            _LOG.warning("nightpanel: claude_code theme write failed: %s", e)

    def _wrapper_installed(self) -> bool:
        """True if ~/.local/bin/claude is our wrapper (not the original symlink)."""
        if not _WRAPPER.exists() or _WRAPPER.is_symlink():
            return False
        try:
            return _WRAPPER_MARKER in _WRAPPER.read_text()
        except OSError:
            return False

    def _install_wrapper(self) -> None:
        """Replace ~/.local/bin/claude with the NP wrapper script.

        Idempotent — does nothing if our wrapper is already in place.
        The real binary keeps living in ~/.local/share/claude/versions/.
        """
        if not _REAL_DIR.exists():
            _LOG.debug("nightpanel: claude versions dir not found, skipping wrapper")
            return
        if self._wrapper_installed():
            return
        try:
            _WRAPPER.parent.mkdir(parents=True, exist_ok=True)
            # If a symlink (the original installer's pointer) is there, unlink
            # it cleanly. The wrapper will discover the real binary via the
            # versions/ glob, so we don't lose anything.
            if _WRAPPER.is_symlink() or _WRAPPER.exists():
                _WRAPPER.unlink()
            _WRAPPER.write_text(_WRAPPER_SCRIPT)
            _WRAPPER.chmod(0o755)
        except OSError as e:
            _LOG.warning("nightpanel: claude wrapper install failed: %s", e)
